ACC = {"Á":("A","a"),"É":("E","a"),"Í":("I","a"),"Ó":("O","a"),"Ú":("U","a"),"Ã":("A","t"),"Õ":("O","t"),
       "Â":("A","c"),"Ê":("E","c"),"Ô":("O","c"),"Ç":("C","d")}
MARK = {"a":["...#.","..#.."],"t":[".##.#","#.##."],"c":["..#..",".#.#."]}

def width(s, scale=1):
    return len(s) * 6 * scale - scale

def draw(d, x, y, s, col, scale=1, center=False, shadow=None):
    """y = topo da letra (acentos ficam 3px acima). center: x é o centro."""
    s = s.upper()
    if center:
        x = x - width(s, scale) // 2
    if shadow:
        draw(d, x + scale, y + scale, s, shadow, scale)
    for i, ch in enumerate(s):
        base, mark = ACC.get(ch, (ch, None))
        rows = G.get(base, G["?"]).split("|")
        cx = x + i * 6 * scale
        def blit(rows, y0):
            for r, row in enumerate(rows):
                for c, v in enumerate(row):
                    if v == "#":
                        d.rectangle([cx + c*scale, y0 + r*scale, cx + (c+1)*scale - 1, y0 + (r+1)*scale - 1], fill=col)
        blit(rows, y)
        if mark in MARK:
            blit(MARK[mark], y - 3 * scale)
        elif mark == "d":
            blit(["..#..", ".#..."], y + 7 * scale)
